/**
 * Static prerender.
 *
 * Renders every English and Arabic route to its own HTML file with the
 * correct <html lang/dir>, title, description, canonical, hreflang, Open
 * Graph and JSON-LD, so crawlers and link previews get complete pages
 * without running JavaScript. Also writes sitemap.xml, robots.txt and the
 * 301 redirect rules for Netlify/Cloudflare (`_redirects`) and Apache
 * (`.htaccess`).
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dist = path.join(root, 'dist')
const SITE = 'https://projects-world.com'

const { render, allPaths, redirects, localePath } = await import(pathToFileURL(path.join(root, 'dist-ssr/entry-server.js')).href)
const template = fs.readFileSync(path.join(dist, 'index.html'), 'utf8')

function page(url, routeAttr = url) {
  const { html, head, locale } = render(url)
  return template
    .replace('<div id="root">', `<div id="root" data-route="${routeAttr}">`)
    .replace('<html lang="en" dir="ltr">', `<html lang="${locale}" dir="${locale === 'ar' ? 'rtl' : 'ltr'}">`)
    .replace('<!--head-->', head)
    .replace('<!--app-->', html)
}

function write(url, contents) {
  const file = url.endsWith('/') ? path.join(dist, url, 'index.html') : path.join(dist, url)
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, contents)
}

const paths = allPaths()
let count = 0
for (const p of paths) {
  for (const locale of ['en', 'ar']) {
    write(localePath(locale, p), page(localePath(locale, p)))
    count++
  }
}
// Error pages are served at arbitrary URLs, so the client re-renders them rather than hydrating
write('/404.html', page('/404/', '*'))
write('/ar/404.html', page('/ar/404/', '*'))

// Sitemap with hreflang alternates for each pair
const today = new Date().toISOString().slice(0, 10)
const urls = paths
  .flatMap((p) =>
    ['en', 'ar'].map(
      (locale) => `  <url>
    <loc>${SITE}${localePath(locale, p)}</loc>
    <lastmod>${today}</lastmod>
    <xhtml:link rel="alternate" hreflang="en" href="${SITE}${localePath('en', p)}"/>
    <xhtml:link rel="alternate" hreflang="ar" href="${SITE}${localePath('ar', p)}"/>
    <xhtml:link rel="alternate" hreflang="x-default" href="${SITE}${localePath('en', p)}"/>
  </url>`,
    ),
  )
  .join('\n')
fs.writeFileSync(
  path.join(dist, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${urls}
</urlset>
`,
)

fs.writeFileSync(path.join(dist, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${SITE}/sitemap.xml\n`)

// Redirects: both locales, with and without trailing slash
const rules = redirects.flatMap(([from, to]) =>
  ['en', 'ar'].flatMap((locale) => {
    const src = localePath(locale, from)
    const dest = localePath(locale, to)
    const bare = src.replace(/\/$/, '')
    return bare && bare !== src ? [[src, dest], [bare, dest]] : [[src, dest]]
  }),
)
fs.writeFileSync(
  path.join(dist, '_redirects'),
  rules.map(([s, d]) => `${s} ${d} 301`).join('\n') + '\n/ar/* /ar/404.html 404\n/* /404.html 404\n',
)
fs.writeFileSync(
  path.join(dist, '.htaccess'),
  `# Generated by scripts/prerender.mjs
RewriteEngine On
DirectorySlash On
ErrorDocument 404 /404.html
${rules.map(([s, d]) => `Redirect 301 ${s} ${d}`).join('\n')}
`,
)

fs.rmSync(path.join(root, 'dist-ssr'), { recursive: true, force: true })
console.log(`Prerendered ${count} pages, sitemap (${paths.length * 2} URLs) and ${rules.length} redirect rules.`)
